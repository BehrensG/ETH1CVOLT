/* USER CODE BEGIN 4 */
void HAL_ETH_ErrorCallback(ETH_HandleTypeDef *heth)
{
    /* Check if the error is a Receive Buffer Unavailable (RBU) */
    if ((HAL_ETH_GetDMAError(heth) & ETH_DMACSR_RBU) != 0U)
    {
        /* Clear the RBU state by forcing a resume of the DMA reception */
        HAL_ETH_Start_IT(heth);
    }
}

